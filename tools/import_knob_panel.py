"""Import only LCD register data from the supplied vendor archive; execute no vendor code."""
import pathlib
import re
import sys
import zipfile

archive = pathlib.Path(sys.argv[1])
destination = pathlib.Path(__file__).resolve().parents[1] / "firmware/main/PanelInit.hpp"
member = "JC3636K718_knob_EN/2-Program Example/Demo_arduino/ST77916_LVGL_DEMO/scr_st77916.h"
with zipfile.ZipFile(archive) as vendor:
    source = vendor.read(member).decode("utf-8").replace("\r", "")
source = source.split("const esp_lcd_panel_vendor_init_cmd_t lcd_init_cmd[] = {", 1)[1].split("};", 1)[0]
commands = re.findall(r"\{(0x[0-9A-Fa-f]+),\s*\(uint8_t\[\]\)\{([^}]+)\},\s*(\d+),\s*(\d+)\}", source)
if len(commands) < 100:
    raise ValueError("Unexpected panel initialization table")
lines = ["// Panel register sequence from Guition JC3636K718_knob_EN vendor demo.",
         "// See docs/hardware.md for provenance. Generated by tools/import_knob_panel.py.",
         "#pragma once", '#include "esp_lcd_st77916.h"']
for index, (_, values, count, _) in enumerate(commands):
    if len(values.split(",")) != int(count):
        raise ValueError("Invalid command payload length")
    lines.append(f"static const uint8_t lcd_data_{index}[] = {{{values}}};")
lines.append("static const st77916_lcd_init_cmd_t lcd_commands[] = {")
for index, (command, _, count, delay) in enumerate(commands):
    lines.append(f" {{{command}, lcd_data_{index}, {count}, {delay}}},")
lines.append("};")
destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Imported {len(commands)} panel initialization commands")
